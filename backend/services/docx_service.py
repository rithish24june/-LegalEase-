import io
import base64
from docx import Document
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT

def generate_docx(doc_item: dict) -> bytes:
    doc = Document()

    # Set Margins (1 inch)
    sections = doc.sections
    for section in sections:
        section.top_margin = Inches(1)
        section.bottom_margin = Inches(1)
        section.left_margin = Inches(1)
        section.right_margin = Inches(1)

    branding = doc_item.get("branding") or {}
    company_name = branding.get("company_name", "")
    footer_text = branding.get("footer_text", "Generated by LegalEase AI Legal Document Platform")
    content = doc_item.get("content", "")
    title = doc_item.get("title", "Legal Document")

    # Branding Header
    if company_name:
        p_header = doc.add_paragraph()
        p_header.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        run_company = p_header.add_run(company_name.upper())
        run_company.font.name = 'Times New Roman'
        run_company.font.size = Pt(10)
        run_company.font.bold = True
        run_company.font.color.rgb = RGBColor(70, 70, 70)

    # Document Title
    p_title = doc.add_paragraph()
    p_title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p_title.paragraph_format.space_before = Pt(12)
    p_title.paragraph_format.space_after = Pt(24)
    run_title = p_title.add_run(title.upper())
    run_title.font.name = 'Times New Roman'
    run_title.font.size = Pt(16)
    run_title.font.bold = True
    run_title.font.color.rgb = RGBColor(20, 35, 60)

    # Split content by lines and format headings vs body paragraphs
    lines = content.split('\n')
    for line in lines:
        line_str = line.strip()
        if not line_str:
            continue
        
        # Check if line is header or numbered clause
        if line_str.startswith("1.") or line_str.startswith("2.") or line_str.startswith("3.") or \
           line_str.startswith("4.") or line_str.startswith("5.") or line_str.startswith("6.") or \
           line_str.isupper() and len(line_str) < 60:
            p = doc.add_paragraph()
            p.paragraph_format.space_before = Pt(14)
            p.paragraph_format.space_after = Pt(4)
            run = p.add_run(line_str)
            run.font.name = 'Times New Roman'
            run.font.size = Pt(12)
            run.font.bold = True
            run.font.color.rgb = RGBColor(30, 45, 75)
        elif line_str.startswith("a)") or line_str.startswith("b)") or line_str.startswith("c)") or line_str.startswith("-"):
            p = doc.add_paragraph()
            p.paragraph_format.left_indent = Inches(0.4)
            p.paragraph_format.space_before = Pt(2)
            p.paragraph_format.space_after = Pt(4)
            run = p.add_run(line_str)
            run.font.name = 'Times New Roman'
            run.font.size = Pt(11)
            run.font.color.rgb = RGBColor(40, 40, 40)
        else:
            p = doc.add_paragraph()
            p.paragraph_format.space_before = Pt(4)
            p.paragraph_format.space_after = Pt(6)
            p.paragraph_format.line_spacing = 1.15
            run = p.add_run(line_str)
            run.font.name = 'Times New Roman'
            run.font.size = Pt(11)
            run.font.color.rgb = RGBColor(30, 30, 30)

    # Footer
    for section in doc.sections:
        footer = section.footer
        p_ft = footer.paragraphs[0]
        p_ft.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run_ft = p_ft.add_run(footer_text)
        run_ft.font.name = 'Times New Roman'
        run_ft.font.size = Pt(9)
        run_ft.font.italic = True
        run_ft.font.color.rgb = RGBColor(120, 120, 120)

    file_stream = io.BytesIO()
    doc.save(file_stream)
    file_stream.seek(0)
    return file_stream.getvalue()
