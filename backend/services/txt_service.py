def generate_txt(doc_item: dict) -> str:
    title = doc_item.get("title", "Legal Document")
    doc_type = doc_item.get("document_type", "Agreement")
    created_at = doc_item.get("created_at", "")
    content = doc_item.get("content", "")
    branding = doc_item.get("branding") or {}
    company_name = branding.get("company_name", "")

    header = f"================================================================================\n"
    if company_name:
        header += f"{company_name.upper()}\n"
    header += f"DOCUMENT: {title}\nTYPE: {doc_type}\nDATE: {created_at}\n"
    header += f"================================================================================\n\n"

    footer = f"\n\n================================================================================\n"
    if branding.get("footer_text"):
        footer += f"{branding.get('footer_text')}\n"
    footer += f"Generated by LegalEase AI Legal Document Platform\n"
    footer += f"================================================================================\n"

    return header + content + footer
